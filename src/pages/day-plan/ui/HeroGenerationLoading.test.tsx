import { act, create, type ReactTestRenderer } from 'react-test-renderer';
import { HeroGenerationLoading } from './HeroGenerationLoading';
jest.mock('@shared/lib/i18n', () => ({ useTranslation: () => ({ t: (key: string, values?: Record<string, unknown>) => `${key}:${JSON.stringify(values ?? {})}` }) }));
jest.mock('@shared/ui/themed-text', () => ({ ThemedText: jest.requireActual('react-native').Text }));
it('shows selected photos and estimated progress that stays below completion until results arrive', () => {
  jest.useFakeTimers();
  const images = [{ uri: 'file:///first.jpg' }, { uri: 'file:///second.jpg' }];
  let tree!: ReactTestRenderer;
  act(() => { tree = create(<HeroGenerationLoading completed={0} total={2} images={images} />); });
  expect(tree.root.findAllByProps({ testID: 'hero-generation-source' }).filter(node => typeof node.type !== 'string').map(node => node.props.source)).toEqual(images);
  const percent = () => tree.root.findAllByProps({ accessibilityRole: 'progressbar' })[0].props.accessibilityValue.now;
  expect(percent()).toBe(0);
  act(() => jest.advanceTimersByTime(91000));
  expect(percent()).toBeGreaterThan(0);
  expect(JSON.stringify(tree.toJSON())).toContain('comicDay.loading.longer');
  expect(JSON.stringify(tree.toJSON())).not.toContain('{{time}}');
  const previous = percent();
  act(() => tree.update(<HeroGenerationLoading completed={1} total={2} images={images} />));
  expect(percent()).toBeGreaterThanOrEqual(previous);
  act(() => jest.advanceTimersByTime(600000));
  expect(percent()).toBeLessThan(100);
  act(() => tree.unmount());
  expect(jest.getTimerCount()).toBe(0);
  jest.useRealTimers();
});
