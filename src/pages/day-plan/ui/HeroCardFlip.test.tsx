import { createRef } from 'react';
import { act, create } from 'react-test-renderer';
import { Animated, Modal, Text } from 'react-native';
import { HeroCardFlip, type HeroCardFlipHandle } from './HeroCardFlip';
jest.mock('@shared/ui/app-modal', () => ({ AppModal: jest.requireActual('react-native').Modal }));
jest.mock('react-native-safe-area-context', () => ({ useSafeAreaInsets: () => ({ top: 44, bottom: 20 }) }));
it.each(['flip', 'fade'] as const)('opens %s details immediately and closes without animation', transition => {
  const timing = jest.spyOn(Animated, 'timing');
  const closed = jest.fn(), restored = jest.fn();
  const ref = createRef<HeroCardFlipHandle>();
  let tree!: ReturnType<typeof create>;
  act(() => { tree = create(<HeroCardFlip ref={ref} transition={transition} paper="#FFF" closeLabel="Close" fallbackFront={<Text>Front</Text>} onClosed={closed} onRestoreFront={restored}><Text>Details</Text></HeroCardFlip>); });
  expect(tree.root.findByType(Modal).props.animationType).toBe('none');
  expect(tree.root.findAllByProps({ children: 'Details' }).length).toBeGreaterThan(0);
  expect(timing).not.toHaveBeenCalled();
  act(() => ref.current!.close());
  expect(restored).toHaveBeenCalledTimes(1);
  act(() => tree.root.findByType(Modal).props.onDismiss());
  expect(closed).toHaveBeenCalledTimes(1);
  act(() => tree.unmount());
  timing.mockRestore();
});
