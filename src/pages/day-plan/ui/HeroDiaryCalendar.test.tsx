import { tapHaptic } from '@shared/lib/haptics/tapHaptic';
import { act, create, type ReactTestRenderer } from 'react-test-renderer';
import { HeroDiaryCalendar } from './HeroDiaryCalendar';
import { AppAlert } from '@shared/lib/app-alert';
import { localStorageClient } from '@shared/lib/storage/localStorageClient';
import { newComicScene } from '../lib/heroDayStorage';
import type { ComicDiary } from '../lib/heroDiaryStorage';
jest.mock('@shared/lib/haptics/tapHaptic', () => ({ tapHaptic: jest.fn() }));
jest.mock('@shared/ui/app-modal', () => ({ AppModal: jest.requireActual('react-native').View }));
jest.mock('@shared/ui/paper-grain', () => ({ PaperGrain: () => null }));
jest.mock('@shared/ui/themed-text', () => ({ ThemedText: jest.requireActual('react-native').Text }));
jest.mock('@shared/lib/i18n', () => ({ useTranslation: () => ({ locale: 'ko', t: (key: string) => key }) }));
jest.mock('./HeroSceneImage', () => ({ ComicSceneImage: () => null }));
jest.mock('@shared/lib/app-alert', () => ({ AppAlert: { alert: jest.fn() } }));
jest.mock('react-native-safe-area-context', () => ({ useSafeAreaInsets: () => ({ top: 0, bottom: 0, left: 0, right: 0 }) }));
afterEach(() => localStorageClient.removeItem('pokit:comic-calendar-covers:v1'));
it('opens each diary on the chosen day, saves a cover, and navigates months without altering diaries', () => {
  const first: ComicDiary = { id: 'a', title: 'morning', characterId: 'protagonist-1', createdAt: new Date(2026, 9, 13, 8).getTime(), updatedAt: 0, scenes: [newComicScene('walk')] };
  const second: ComicDiary = { ...first, id: 'b', title: 'evening', createdAt: new Date(2026, 9, 13, 20).getTime(), scenes: [newComicScene('read')] };
  const onOpen = jest.fn(), onClose = jest.fn();
  let tree!: ReactTestRenderer;
  act(() => { tree = create(<HeroDiaryCalendar diaries={[first, second]} today="2026-10-29" ink="#222" muted="#777" isDark={false} onOpen={onOpen} onClose={onClose} />); });
  const button = (label: string) => tree.root.findAll(node => node.props.accessibilityLabel === label && typeof node.props.onPress === 'function')[0];
  jest.mocked(tapHaptic).mockClear();
  act(() => tree.root.findAllByProps({ testID: 'comic-calendar-day-2026-10-13' })[0].props.onPress());
  expect(tapHaptic).toHaveBeenCalledTimes(1);
  expect(tapHaptic).toHaveBeenCalledWith('select');
  jest.mocked(tapHaptic).mockClear();
  expect(tree.root.findAllByProps({ testID: 'comic-calendar-more' }).length).toBeGreaterThan(0);
  const list = tree.root.findAllByProps({ testID: 'comic-calendar-diary-scroll' })[0];
  act(() => list.props.onScroll({ nativeEvent: { contentOffset: { y: 220 }, layoutMeasurement: { height: 220 }, contentSize: { height: 440 } } }));
  expect(tree.root.findAllByProps({ testID: 'comic-calendar-more' })).toHaveLength(0);
  act(() => list.props.onScroll({ nativeEvent: { contentOffset: { y: 0 }, layoutMeasurement: { height: 220 }, contentSize: { height: 440 } } }));
  expect(tree.root.findAllByProps({ testID: 'comic-calendar-more' }).length).toBeGreaterThan(0);
  expect(tapHaptic).not.toHaveBeenCalled();
  const scene = button('evening, read');
  act(() => scene.props.onPress());
  expect(onOpen).toHaveBeenCalledWith('b');
  expect(tapHaptic).toHaveBeenCalledTimes(1);
  expect(tapHaptic).toHaveBeenCalledWith();
  act(() => scene.props.onLongPress());
  const actions = jest.mocked(AppAlert.alert).mock.calls.at(-1)![2]!;
  act(() => actions[1].onPress?.());
  expect(localStorageClient.getJson('pokit:comic-calendar-covers:v1')).toEqual({ '2026-10-13': { diaryId: 'b', sceneId: second.scenes[0].id } });
  act(() => button('comicCalendar.next').props.onPress());
  expect(tree.root.findAllByProps({ testID: 'comic-calendar-day-2026-11-01' }).length).toBeGreaterThan(0);
  act(() => button('comicCalendar.previous').props.onPress());
  expect(tree.root.findAllByProps({ testID: 'comic-calendar-day-2026-10-29' })[0].props.accessibilityState.selected).toBe(true);
  act(() => button('common.close').props.onPress());
  expect(onClose).toHaveBeenCalledTimes(1);
  expect(first.scenes).toHaveLength(1);
  act(() => tree.unmount());
});
