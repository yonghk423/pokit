"""Bake the existing SVG RGB multiplication into 8-bit sRGB PNGs for iOS."""
import re
from pathlib import Path
from PIL import Image, ImageChops, PngImagePlugin

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'assets/stationery-desk'
OUT = ASSETS / 'tinted'
OUT.mkdir(exist_ok=True)
MARKERS = ['red', 'peach', 'yellow', 'mint', 'lavender', 'indigo', 'violet']
mark_source = (ROOT / 'src/entities/day-plan/lib/priorityMarkColor.ts').read_text()
colors = {'highlighter': []}
for name in MARKERS:
    match = re.search(r"id: '" + name + r"',\s*face: '(#[0-9a-fA-F]{6})',\s*faceDark: '(#[0-9a-fA-F]{6})'", mark_source)
    if not match:
        raise ValueError(f'Missing marker: {name}')
    colors['highlighter'].extend([match[1].lower(), match[2].lower()])
metadata = PngImagePlugin.PngInfo()
metadata.add(b'sRGB', b'\x00')
lines = ['// Generated by scripts/prepare-stationery-colors.py; no runtime SVG filters.', 'export const STATIONERY_COLOR_IMAGES = {']
expected = set()
for kind, values in colors.items():
    source = Image.open(ASSETS / 'highlighter.png').convert('RGBA')
    alpha = source.getchannel('A')
    lines.append(f'  {kind}: {{')
    for color in dict.fromkeys(values):
        # Same per-channel multiplication as the removed FeColorMatrix.
        rgb = ImageChops.multiply(source.convert('RGB'), Image.new('RGB', source.size, color))
        rgba = rgb.convert('RGBA')
        rgba.putalpha(alpha)
        filename = f'{kind}-{color[1:]}.png'
        rgba.save(OUT / filename, pnginfo=metadata, optimize=True)
        expected.add(filename)
        lines.append(f"    '{color}': require('../../../../assets/stationery-desk/tinted/{filename}'),")
    lines.append('  },')
lines.append('} as const;\n')
(ROOT / 'src/shared/ui/stationery-tool/colorImages.ts').write_text('\n'.join(lines))
for old in OUT.glob('*.png'):
    if old.name not in expected:
        old.unlink()
print(f'{len(expected)} sRGB RGBA images: {sum((OUT / name).stat().st_size for name in expected)} bytes')
